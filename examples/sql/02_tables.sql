-- Isabel sample dataset, step 2: tables. Primary and foreign keys are
-- informational in Snowflake; they document the joins the semantic model uses.
USE SCHEMA ISABEL_SAMPLE.SECURITY;

CREATE OR REPLACE TABLE TEAMS (
  TEAM_ID              VARCHAR(20)  NOT NULL PRIMARY KEY,
  TEAM_NAME            VARCHAR(100) NOT NULL,
  ORGANIZATION         VARCHAR(100),
  TEAM_LEAD            VARCHAR(100),
  SECURITY_CHAMPION    VARCHAR(100),
  CONTACT_EMAIL        VARCHAR(200),
  LAST_ASSESSMENT_DATE DATE,
  ASSESSMENT_SCORE     NUMBER(5,1)
);

CREATE OR REPLACE TABLE APPLICATIONS (
  APPLICATION_ID    NUMBER(10,0) NOT NULL PRIMARY KEY,
  APPLICATION_NAME  VARCHAR(100) NOT NULL,
  APPLICATION_GROUP VARCHAR(100),
  CRITICALITY       VARCHAR(20),
  SERVICE_LEVEL     VARCHAR(20),
  LIFECYCLE_STATUS  VARCHAR(30),
  INTERNET_FACING   BOOLEAN,
  TEAM_ID           VARCHAR(20) REFERENCES TEAMS (TEAM_ID)
);

CREATE OR REPLACE TABLE VULNERABILITY_CATALOG (
  CATALOG_ID       NUMBER(10,0) NOT NULL PRIMARY KEY,
  TITLE            VARCHAR(300) NOT NULL,
  SEVERITY         VARCHAR(20),
  CATEGORY         VARCHAR(50),
  CVE_ID           VARCHAR(30),
  CVSS_SCORE       NUMBER(3,1),
  EPSS_SCORE       NUMBER(5,4),
  ACTIVELY_EXPLOITED VARCHAR(10),
  PUBLISHED_DATE   DATE,
  SUMMARY          VARCHAR(2000),
  THREAT           VARCHAR(2000),
  SOLUTION         VARCHAR(2000)
);

CREATE OR REPLACE TABLE HOST_VULNERABILITIES (
  FINDING_ID          VARCHAR(30)  NOT NULL PRIMARY KEY,
  CATALOG_ID          NUMBER(10,0) REFERENCES VULNERABILITY_CATALOG (CATALOG_ID),
  APPLICATION_ID      NUMBER(10,0) REFERENCES APPLICATIONS (APPLICATION_ID),
  TEAM_ID             VARCHAR(20)  REFERENCES TEAMS (TEAM_ID),
  HOSTNAME            VARCHAR(200),
  IP_ADDRESS          VARCHAR(45),
  OPERATING_SYSTEM    VARCHAR(100),
  PORT                NUMBER(5,0),
  PROTOCOL            VARCHAR(10),
  SEVERITY            VARCHAR(20),
  STATUS              VARCHAR(20),
  REMEDIATION_STATUS  VARCHAR(30),
  FIRST_DETECTED_DATE DATE,
  LAST_DETECTED_DATE  DATE,
  DUE_DATE            DATE,
  RESOLVED_DATE       DATE
);

CREATE OR REPLACE TABLE CODE_FINDINGS (
  FINDING_ID        VARCHAR(40)  NOT NULL PRIMARY KEY,
  APPLICATION_ID    NUMBER(10,0) REFERENCES APPLICATIONS (APPLICATION_ID),
  TEAM_ID           VARCHAR(20)  REFERENCES TEAMS (TEAM_ID),
  REPOSITORY        VARCHAR(200),
  TITLE             VARCHAR(300),
  SEVERITY          VARCHAR(20),
  STATUS            VARCHAR(20),
  CVE_ID            VARCHAR(30),
  LIBRARY_NAME      VARCHAR(100),
  LIBRARY_VERSION   VARCHAR(40),
  FIXED_VERSION     VARCHAR(40),
  EXPLOIT_MATURITY  VARCHAR(30),
  CREATED_DATE      DATE,
  DUE_DATE          DATE,
  RESOLVED_DATE     DATE
);
