-- Isabel sample dataset, step 1: account objects.
-- Run as ACCOUNTADMIN (or a role that can create roles, users and warehouses).
-- Replace the RSA_PUBLIC_KEY placeholder with the body of your public key
-- (the base64 between the BEGIN/END PUBLIC KEY lines, without the dashes).

CREATE WAREHOUSE IF NOT EXISTS ISABEL_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ISABEL_SAMPLE;
CREATE SCHEMA IF NOT EXISTS ISABEL_SAMPLE.SECURITY;

-- Holds semantic_model.yaml. Cortex Analyst needs server-side encryption.
CREATE STAGE IF NOT EXISTS ISABEL_SAMPLE.SECURITY.MODELS
  DIRECTORY = (ENABLE = TRUE)
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

CREATE ROLE IF NOT EXISTS ISABEL_APP_ROLE;
GRANT ROLE ISABEL_APP_ROLE TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE ISABEL_WH TO ROLE ISABEL_APP_ROLE;
GRANT USAGE ON DATABASE ISABEL_SAMPLE TO ROLE ISABEL_APP_ROLE;
GRANT USAGE ON SCHEMA ISABEL_SAMPLE.SECURITY TO ROLE ISABEL_APP_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ISABEL_SAMPLE.SECURITY TO ROLE ISABEL_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA ISABEL_SAMPLE.SECURITY TO ROLE ISABEL_APP_ROLE;
GRANT READ ON STAGE ISABEL_SAMPLE.SECURITY.MODELS TO ROLE ISABEL_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ISABEL_APP_ROLE;

-- Service user the app signs in as (key-pair auth, no password).
CREATE USER IF NOT EXISTS ISABEL_APP
  TYPE = SERVICE
  DEFAULT_ROLE = ISABEL_APP_ROLE
  DEFAULT_WAREHOUSE = ISABEL_WH
  RSA_PUBLIC_KEY = '<RSA_PUBLIC_KEY>';
GRANT ROLE ISABEL_APP_ROLE TO USER ISABEL_APP;
